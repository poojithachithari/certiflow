// Certificate PDF with a QR code pointing at the public verification page.
// Written to a temp file then renamed: rename is atomic, so a crash mid-write never leaves
// a half-written PDF that later looks "done".
import fs from "node:fs";
import path from "node:path";
import PDFDocument from "pdfkit";
import QRCode from "qrcode";
import { config } from "../config";
import { verificationCode, verifyUrl } from "./certificates";

export interface CertificatePdfData {
  number: string;
  holderName: string;
  enrolmentNo: string;
  courseName: string;
  centreName: string;
  issuedAt: Date;
}

export async function ensureCertificatePdf(data: CertificatePdfData): Promise<string> {
  const relative = `${data.number}.pdf`;
  const root = path.resolve(config.CERT_STORAGE_DIR);
  const finalPath = path.join(root, relative);
  if (fs.existsSync(finalPath)) return relative; // idempotent: already generated by an earlier attempt
  fs.mkdirSync(root, { recursive: true });

  const qr = await QRCode.toBuffer(verifyUrl(data.number), { margin: 1, width: 220 });
  const tmp = `${finalPath}.${process.pid}.${Date.now()}.tmp`;

  await new Promise<void>((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", layout: "landscape", margin: 50 });
    const out = fs.createWriteStream(tmp);
    out.on("finish", resolve);
    out.on("error", reject);
    doc.pipe(out);

    const w = doc.page.width;
    doc.rect(25, 25, w - 50, doc.page.height - 50).lineWidth(3).stroke("#0d6b58");
    doc.fillColor("#0d6b58").fontSize(14).text("PRAGATI SKILLS MISSION", 0, 70, { align: "center", characterSpacing: 3 });
    doc.fillColor("#16211e").fontSize(34).text("Certificate of Skill", 0, 100, { align: "center" });
    doc.fontSize(14).fillColor("#586863").text("This certifies that", 0, 165, { align: "center" });
    doc.fontSize(28).fillColor("#16211e").text(data.holderName, 0, 190, { align: "center" });
    doc.fontSize(13).fillColor("#586863").text(`Enrolment no. ${data.enrolmentNo}`, 0, 230, { align: "center" });
    doc.fontSize(14).fillColor("#586863").text("has successfully completed", 0, 265, { align: "center" });
    doc.fontSize(22).fillColor("#16211e").text(data.courseName, 0, 290, { align: "center" });
    doc.fontSize(13).fillColor("#586863").text(`at ${data.centreName}`, 0, 325, { align: "center" });

    doc.fontSize(11).fillColor("#16211e");
    doc.text(`Certificate no.  ${data.number}`, 70, 430);
    doc.text(`Verification code  ${verificationCode(data.number)}`, 70, 448);
    doc.text(`Issued  ${data.issuedAt.toISOString().slice(0, 10)}`, 70, 466);
    doc.fillColor("#586863").fontSize(9).text(`Check this certificate at ${config.PUBLIC_BASE_URL}/verify`, 70, 490);
    doc.image(qr, w - 70 - 110, 400, { width: 110 });
    doc.end();
  });

  fs.renameSync(tmp, finalPath);
  return relative;
}
